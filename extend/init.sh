#!/usr/bin/env bash
# vault-quality-gates — the `init` extension point.
#
# The vault framework runs this during bin/vault-init.sh, after VAULT.md exists, through this
# shebang in a child process with stdin closed. Arguments: <code-repo> <vault-dir> <slug>.
#
# It leaves the target repo able to answer, without reading anything in this repo:
#   - what this plugin is and where it is installed
#   - the nine columns of quality/checks.tsv and every legal value
#   - which parsers actually ship, listed from lib/guard-parsers/ so the list cannot drift
#   - the exact next step
#
# That last point is the whole job. A scaffold that writes a config file and no instructions makes
# the next session design the system from a header comment.
#
# Exit 0 on every path. Running twice changes nothing the second time.

set -u

PLUGIN_NAME="vault-quality-gates"
MARK_START="<!-- ${PLUGIN_NAME}:start — regenerated by extend/init.sh; edit outside this block -->"
MARK_END="<!-- ${PLUGIN_NAME}:end -->"

# Resolved at run time, so the path written into the target repo is always the real install.
PLUGIN_ROOT=$(cd "$(dirname "$0")/.." 2>/dev/null && pwd) || exit 1

code_repo=${1:-}
[ -n "${code_repo}" ] || exit 0

vault_md="${code_repo}/VAULT.md"
[ -f "${vault_md}" ] || exit 0

mkdir -p "${code_repo}/quality" || exit 1

# --- what ships, read from disk rather than restated ---------------------------------------

parsers=""
for f in "${PLUGIN_ROOT}"/lib/guard-parsers/*.sh; do
    [ -f "$f" ] || continue
    b=$(basename "$f" .sh)
    case "$b" in _*) continue ;; esac
    parsers="${parsers}${parsers:+, }\`${b}\`"
done
[ -n "${parsers}" ] || parsers="none — \`${PLUGIN_ROOT}/lib/guard-parsers/\` is empty"

runner_state="present"
[ -x "${PLUGIN_ROOT}/bin/guard.sh" ] || runner_state="NOT BUILT — \`${PLUGIN_ROOT}/bin/guard.sh\` does not exist yet"

# --- quality/checks.tsv and quality/config -------------------------------------------------
#
# qg init with the docs profile: every repo the vault framework sets up carries documents, and
# that profile's rows gate only them. A stack profile replaces it (`qg init --profile <p> --force`);
# a guessed stack row gates a push on a tool nobody chose.

if [ ! -f "${code_repo}/quality/checks.tsv" ]; then
    (
        cd "${code_repo}" || exit 1
        GUARD_LIB_DIR="${PLUGIN_ROOT}/lib"
        qg_die() { printf 'qg: %s\n' "$*" >&2; exit 2; }
        # shellcheck source=../lib/qg-init.sh
        . "${GUARD_LIB_DIR}/qg-init.sh"
        qg_init --profile docs > /dev/null
    ) || printf '  %s: qg init --profile docs failed; a human runs it in %s\n' "${PLUGIN_NAME}" "${code_repo}" >&2
fi

# --- quality/README.md: the brief the next session actually reads ---------------------------

readme="${code_repo}/quality/README.md"
block=$(cat <<EOF
${MARK_START}

# Quality gates — this repo

This repo is wired to **${PLUGIN_NAME}**, installed at:

\`\`\`
${PLUGIN_ROOT}
\`\`\`

It refuses a \`git push\` to a release branch when a measured metric is worse than the baseline
committed in \`quality/baseline.tsv\`. Every other push is untouched.

**Runner:** ${runner_state}

**Exit codes, everywhere:** 0 measured and acceptable · 1 measured and worse · 2 could not measure.
A check that could not run is never recorded as passing.

## Wiring this repo is data, not code

You write **rows**, into the two files below. You do not write shell scripts, git hooks, a runner or
a report generator — they ship with the plugin and are listed above. A parallel implementation in
this repo cost one session most of its length and was deleted whole.

1. **Read \`${PLUGIN_ROOT}/vault/plans/2026-09-14-1251-quality-regression-gate.md\`** — the
   specification: work items, file formats, decisions, success criteria. A \`vault/plans/*.md\` in a
   repo you are about to change is a build order, not background reading.
2. Read \`${PLUGIN_ROOT}/vault/architecture/guard-file-formats.md\` — the full contract. It is a
   contract to satisfy, not reference material.
3. Work out which tools this repo already has. Read its \`composer.json\`, \`package.json\`,
   \`Makefile\` or \`pubspec.yaml\` for commands that already exist. Prefer them over new ones.
   Before proposing a new tool, check it exists and is maintained: a recommendation carries a
   version and a release date, or it is not made.
4. **Run each command once before you write its row.** Capture the artifact it leaves. A row whose
   command was never run gates a push on a guess.
5. Add the row to \`quality/checks.tsv\`. Then a human runs \`qg baseline\` and commits
   \`quality/baseline.tsv\`. \`qg init\` wrote the docs starter rows; a stack profile replaces them
   with \`qg init --profile php|nuxt|flutter|hugo --force\`.

The hooks are **git hooks** in \`.git/hooks/\`, not Claude Code hooks. A refusal reaches an agent
because it ran \`git commit\` or \`git push\` and read stderr. \`qg explain <id>\` tells it how to pass.

## quality/checks.tsv — nine columns, tab separated

Line 1 is the literal header. A row whose field count differs is refused, not parsed.

| column | legal values | meaning |
|---|---|---|
| \`id\` | \`^[a-z][a-z0-9-]*\$\`, unique | the metric name in the report and the baseline |
| \`on\` | \`commit\` · \`push\` · \`push:<ref-glob>\` · \`baseline\`, comma-separated, or \`-\` | which runs measure it; \`baseline\` is never run by a hook |
| \`kind\` | \`repo\` · \`diff\` · \`absent\` | \`repo\` compares to the baseline; \`diff\` to \`threshold\` as an absolute floor; \`absent\` runs nothing |
| \`driver\` | \`shell\`, a built-in (\`qg drivers\`), or \`quality/drivers/<name>.sh\` | the wrapper that measures |
| \`args\` | \`[key=value ...] [-- <argv>]\`, or \`-\` | for \`shell\`: \`[parser=<name>] [artifact=<path>] -- <command>\` |
| \`direction\` | \`up\` · \`down\` · \`-\` | \`up\` when higher is better |
| \`threshold\` | a number, or \`-\` | \`kind: repo\` → worsening tolerated; \`kind: diff\` → the absolute floor or ceiling |
| \`gate\` | \`refuse\` · \`warn\` · \`record\` · \`-\` | \`refuse\` exits 1; \`warn\` records and passes; \`record\` stores the number only |
| \`why\` | one sentence | why the gate exists; the refusal prints it, and a row without one does not load |

**Parsers that ship, for \`shell\` rows:** ${parsers}

Each reads one artifact and prints one number. Their source is
\`${PLUGIN_ROOT}/lib/guard-parsers/\` — read the one you plan to use before writing its row.

**Why \`kind: diff\` never compares to a baseline:** each release push measures a different set of
changed lines, so two scores describe different populations.

## quality/baseline.tsv — the ratchet

Four columns: \`id\`, \`value\`, \`commit\`, \`reason\`. Only \`kind: repo\` ids appear. Committed, so
the ratchet travels with the branch and is visible in review.

## Two rules that bite

1. **Nothing whole-repo runs at push time.** A suite that takes an hour makes the gate unusable and
   it gets bypassed. Slow measurements carry \`on: baseline\` and run out of band.
2. **A tool that fails is not a tool that passed.** Exit 2 refuses. Never record a null as a pass.

${MARK_END}
EOF
)

if [ ! -f "${readme}" ]; then
    printf '%s\n' "${block}" > "${readme}" || exit 1
elif grep -qF "${MARK_START}" "${readme}"; then
    # Regenerate only the delimited block, so anything the operator wrote around it survives.
    tmp=$(mktemp) || exit 1
    awk -v s="${MARK_START}" -v e="${MARK_END}" -v repl="${block}" '
        index($0, s) { print repl; skip = 1; next }
        index($0, e) { skip = 0; next }
        !skip { print }
    ' "${readme}" > "${tmp}" && mv "${tmp}" "${readme}" || { rm -f "${tmp}"; exit 1; }
else
    printf '\n%s\n' "${block}" >> "${readme}" || exit 1
fi

# --- CLAUDE.md: the file a session reads without being told ---------------------------------

claude_md="${code_repo}/CLAUDE.md"
if [ -f "${claude_md}" ] && ! grep -q "${PLUGIN_NAME}" "${claude_md}"; then
    [ -n "$(tail -c1 "${claude_md}")" ] && printf '\n' >> "${claude_md}"
    cat >> "${claude_md}" <<EOF

## Quality gates

This repo is wired to the \`${PLUGIN_NAME}\` plugin: a push to a release branch is refused when a
measured metric is worse than \`quality/baseline.tsv\`.

**Read \`quality/README.md\` before touching \`quality/checks.tsv\`.** Wiring this repo is data:
rows in two TSV files. The runner, the git hooks and the parsers ship with the plugin — do not write
your own. That file carries the columns, the parsers, and the plan that specifies all of it.
EOF
fi

# --- merge into the plugins scalar ----------------------------------------------------------

[ -n "$(tail -c1 "${vault_md}")" ] && printf '\n' >> "${vault_md}"

if [ "$(grep -c '^plugins:' "${vault_md}")" -gt 1 ]; then
    printf '  %s: VAULT.md has more than one plugins: line — writing nothing\n' "${PLUGIN_NAME}" >&2
    exit 1
fi

current=$(sed -n 's/^plugins:[[:space:]]*//p' "${vault_md}" | head -1 | tr -d '\r')

if ! grep -q '^plugins:' "${vault_md}"; then
    printf 'plugins: %s\n' "${PLUGIN_NAME}" >> "${vault_md}"
elif [ -z "${current}" ]; then
    sed -i "s|^plugins:.*|plugins: ${PLUGIN_NAME}|" "${vault_md}"
elif printf '%s' "${current}" | tr ',' '\n' | tr -d '[:space:]' | grep -qx "${PLUGIN_NAME}"; then
    :
else
    sed -i "s|^\(plugins:.*\)$|\1, ${PLUGIN_NAME}|" "${vault_md}"
fi

printf '  %s: wrote quality/README.md — read it before quality/checks.tsv\n' "${PLUGIN_NAME}"
exit 0
